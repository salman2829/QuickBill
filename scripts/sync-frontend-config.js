/**
 * Reads client/.env (API_BASE_URL) and writes browser config files.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envPath = path.join(root, 'client', '.env');
const examplePath = path.join(root, 'client', '.env.example');

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const out = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    out[key] = val;
  }
  return out;
}

const env = { ...parseEnv(examplePath), ...parseEnv(envPath) };
const apiBase = process.env.API_BASE_URL || env.API_BASE_URL || '/api';

const contents = `// Generated by scripts/sync-frontend-config.js — edit client/.env then run: npm run sync:config
window.QB_CONFIG = {
  API_BASE_URL: ${JSON.stringify(apiBase)}
};
`;

const targets = [
  path.join(root, 'public', 'js', 'config.js'),
  path.join(root, 'client', 'js', 'config.js')
];

for (const target of targets) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents, 'utf8');
  console.log(`[sync:config] Wrote ${path.relative(root, target)} → ${apiBase}`);
}
